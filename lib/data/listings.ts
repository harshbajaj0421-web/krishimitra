export function getListing(slug: string) {
  return listings.find((listing) => listing.slug === slug)
}

export function similarListings(slug: string, limit = 3) {
  const current = getListing(slug)
  if (!current) return listings.slice(0, limit)
  return listings
    .filter((l) => l.slug !== slug && l.status !== "sold-out")
    .sort((a, b) => {
      const aScore = (a.category === current.category ? 0 : 1) + Math.abs(a.distanceKm - current.distanceKm) / 1000
      const bScore = (b.category === current.category ? 0 : 1) + Math.abs(b.distanceKm - current.distanceKm) / 1000
      return aScore - bScore
    })
    .slice(0, limit)
}
